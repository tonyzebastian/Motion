/* width of a string at a given cap height, including tracking */
function textWidth(str, cap, track, cond = 1) {
  let w = 0;
  for (const ch of str.toUpperCase()) { const g = GLYPHS[ch] || GLYPHS[' ']; w += g.w * cap * cond + track * (.45 + .55 * g.w); }
  return w - track;
}

/* draw a line of hand-lettering centred on cx, baseline at by */
function letter(pen, str, cx, by, cap, o = {}) {
  const track = o.track ?? cap * .28, ink = o.ink || 'blue', wid = o.w ?? 2.4, cond = o.cond ?? 1;
  let x = cx - textWidth(str, cap, track, cond) / 2;
  let k = 0;
  for (const ch of str.toUpperCase()) {
    const g = GLYPHS[ch] || GLYPHS[' '];
    const R = stream('ltr', str, k);
    const dy = rand(R, -.035, .035) * cap;           // letters never sit quite on the line
    const sc = 1 + rand(R, -.04, .04), sl = rand(R, -.05, .05);
    for (const poly of g.s) {
      const P = poly.map(([a, b]) => [x + (a + b * sl) * cap * sc * cond, by - cap + b * cap * sc + dy]);
      pen.line(P, ink, wid, { amp: cap * .035, tone: o.tone ?? 1 });
    }
    x += g.w * cap * cond + track * (.45 + .55 * g.w); k++;
  }
}
