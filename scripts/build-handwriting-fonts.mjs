#!/usr/bin/env node
// Turns single-line SVG fonts (each letter is a pen path, not an outline)
// into small TypeScript modules the HandWrite component can draw stroke by stroke.
//
// Source: the EMS fonts from the `hersheytext` package (SIL Open Font License).
//   curl -sL https://registry.npmjs.org/hersheytext/-/hersheytext-2.0.0.tgz | tar xz
//   node scripts/build-handwriting-fonts.mjs package/svg_fonts
//
// Output: src/scenes/JunyStudios/shared/handwriting/fonts/<name>.ts
//   { unitsPerEm, xHeight, glyphs: { "a": { adv, strokes: [[x, y, x, y, …], …] } } }
// Coordinates are font units with y pointing up, as in the source.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) {
  console.error("Usage: node scripts/build-handwriting-fonts.mjs <svg_fonts dir>");
  process.exit(1);
}
const OUT = "src/scenes/JunyStudios/shared/handwriting/fonts";
const FONTS = { felix: "EMSFelix.svg", allure: "EMSAllure.svg" };

const ENTITIES = { "&amp;": "&", "&quot;": '"', "&lt;": "<", "&gt;": ">", "&apos;": "'" };
const decode = (s) =>
  s
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d)))
    .replace(/&\w+;/g, (e) => ENTITIES[e] ?? e);

const attr = (tag, name) => tag.match(new RegExp(`\\s${name}="([^"]*)"`))?.[1];

mkdirSync(OUT, { recursive: true });
for (const [name, file] of Object.entries(FONTS)) {
  const src = readFileSync(join(dir, file), "utf8");
  const fontTag = src.match(/<font [^>]*>/)[0];
  const faceTag = src.match(/<font-face[^>]*>/)[0];
  const defAdv = Number(attr(fontTag, "horiz-adv-x"));
  const glyphs = {};
  for (const [tag] of src.matchAll(/<glyph [^>]*>/g)) {
    const u = attr(tag, "unicode");
    if (u === undefined) continue;
    const ch = decode(u);
    const d = attr(tag, "d") ?? "";
    // Nearly every glyph is straight M/L segments. A few rare ones use
    // curves; skip those rather than draw them wrong.
    if (/[^ML\d\s.\-]/.test(d)) continue;
    const strokes = [];
    for (const part of d.split("M").map((p) => p.trim()).filter(Boolean)) {
      const nums = part.replace(/L/g, " ").trim().split(/\s+/).map(Number);
      if (nums.length >= 4) strokes.push(nums.map((n) => Math.round(n * 10) / 10));
    }
    glyphs[ch] = { adv: Number(attr(tag, "horiz-adv-x") ?? defAdv), strokes };
  }
  // Typographic quotes fall back to the straight ones.
  for (const [curly, straight] of [["’", "'"], ["‘", "'"], ["“", '"'], ["”", '"']]) {
    glyphs[curly] ??= glyphs[straight];
  }
  const out = {
    name: src.match(/Font name:\s*(.+)/)?.[1].trim(),
    license: "SIL Open Font License 1.1",
    unitsPerEm: Number(attr(faceTag, "units-per-em")),
    xHeight: Number(attr(faceTag, "x-height")),
    glyphs,
  };
  writeFileSync(
    join(OUT, `${name}.ts`),
    `// Generated by scripts/build-handwriting-fonts.mjs from ${out.name} (${out.license}).\n` +
      `import type { HandFont } from "../types";\n\n` +
      `export const ${name}: HandFont = ${JSON.stringify(out)};\n`,
  );
  console.log(`${name}: ${Object.keys(glyphs).length} glyphs`);
}
